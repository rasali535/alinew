require('dotenv').config({ path: 'apps/ralion/.env.local' });
require('dotenv').config({ path: 'apps/ralion/.env' });
require('dotenv').config();

const { SocialPublishingService } = require('../apps/ralion/src/lib/services/social/socialPublishing.service');
const { FacebookPageManagementService } = require('../apps/ralion/src/lib/services/social/facebookPageManagement.service');

async function testUiPublishingFlow() {
  console.log('=====================================================================');
  console.log('RALION OS — UI PUBLISHING PIPELINE END-TO-END VERIFICATION');
  console.log('=====================================================================\n');

  let passed = 0;
  let total = 0;

  function assert(condition, testName, detail = '') {
    total++;
    if (condition) {
      console.log(`✅ [PASS] ${testName} ${detail ? `(${detail})` : ''}`);
      passed++;
    } else {
      console.error(`❌ [FAIL] ${testName} ${detail ? `(${detail})` : ''}`);
    }
  }

  // 1. Verify Destination Resolution
  console.log('\n[1] Verifying Connected Facebook Destination:');
  const pages = await FacebookPageManagementService.discoverAvailablePages({
    userId: 'default-user',
    profileId: '6a82deac1a69158ef81cb2cd',
  });
  assert(pages.pages.length > 0, 'Discovered Facebook Pages', `Count: ${pages.pages.length}`);
  const primaryPage = pages.pages[0];
  assert(primaryPage.pageId === '477334159265235', 'Facebook Page ID Match', primaryPage.pageId);

  // 2. Test UI TEXT-ONLY Publishing Request (exact payload format generated by Content Composer)
  console.log('\n[2] Testing UI Text-Only Publishing Request:');
  const textUiPayload = {
    userId: 'default-user',
    organizationId: 'org_ralion_prod',
    title: 'UI publishing test from Ralion OS.',
    body: 'UI publishing test from Ralion OS. #RalionOS #RasAliLabs #EnterpriseAI',
    platforms: ['facebook'],
    authorName: 'Ras Ali Labs',
    socialConnectionId: '6a82df7277555aae018b92b4',
    pageId: '477334159265235',
  };

  try {
    const textResult = await SocialPublishingService.publish(textUiPayload);
    assert(textResult.postId !== undefined, 'Text Post ID Generated', textResult.postId);
    assert(textResult.overallStatus === 'PUBLISHED', 'Text Post Publishing Status', textResult.overallStatus);
    assert(
      textResult.platformResults.facebook?.success === true,
      'Facebook Text Post Platform Result',
      textResult.platformResults.facebook?.postUrl || 'Success'
    );
  } catch (err) {
    assert(false, 'Text-Only Publishing Execution', err.message);
  }

  // 3. Test UI TEXT + IMAGE Publishing Request
  console.log('\n[3] Testing UI Text + Image Publishing Request:');
  const imageUiPayload = {
    userId: 'default-user',
    organizationId: 'org_ralion_prod',
    title: 'Visual Content Post',
    body: 'Showcasing Ralion OS Enterprise AI with media attachment. #RalionOS #RasAliLabs',
    mediaUrls: ['https://images.unsplash.com/photo-1540575467063-178a50c2df87?w=800&auto=format&fit=crop'],
    mediaTypes: ['image'],
    platforms: ['facebook'],
    authorName: 'Ras Ali Labs',
    socialConnectionId: '6a82df7277555aae018b92b4',
    pageId: '477334159265235',
  };

  try {
    const imgResult = await SocialPublishingService.publish(imageUiPayload);
    assert(imgResult.postId !== undefined, 'Image Post ID Generated', imgResult.postId);
    assert(imgResult.overallStatus === 'PUBLISHED', 'Image Post Publishing Status', imgResult.overallStatus);
    assert(
      imgResult.platformResults.facebook?.success === true,
      'Facebook Image Post Platform Result',
      imgResult.platformResults.facebook?.postUrl || 'Success'
    );
  } catch (err) {
    assert(false, 'Text+Image Publishing Execution', err.message);
  }

  // 4. Verify Live Facebook Page Feed Query
  console.log('\n[4] Ingesting Live Facebook Posts from Page Feed:');
  const livePosts = await FacebookPageManagementService.getPagePosts({
    userId: 'default-user',
    limit: 10,
  });
  assert(livePosts.length >= 4, 'Live Posts Query Ingestion', `Total Posts: ${livePosts.length}`);
  assert(livePosts[0].permalink.includes('facebook.com'), 'Facebook Post Permalink Validation', livePosts[0].permalink);

  console.log('\n=====================================================================');
  console.log(`VERIFICATION COMPLETE: ${passed} / ${total} TESTS PASSED`);
  console.log('=====================================================================');

  if (passed === total) {
    console.log('\n>>> STATUS: FACEBOOK UI PUBLISHING READY <<<');
  } else {
    console.log('\n>>> STATUS: FACEBOOK UI PUBLISHING NOT READY <<<');
  }
}

testUiPublishingFlow().catch(console.error);
